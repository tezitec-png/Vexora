  const LANGS = [ "en", "es", "de", "fr", "it" ];
  function norm(l) {
    l = String(l || "en").toLowerCase().slice(0, 2);
    return LANGS.indexOf(l) >= 0 ? l : "en";
  }
  let lang = "en";
  try {
    lang = norm(localStorage.getItem("vexora.lang") || "en");
  } catch (e) {
    lang = "en";
  }
  function t(key, vars) {
    const d = DICT[lang] || DICT.en;
    let s = d[key];
    if (s == null) s = DICT.en[key] != null ? DICT.en[key] : key;
    if (vars) Object.keys(vars).forEach(k => {
      s = s.split("{" + k + "}").join(String(vars[k]));
    });
    return s;
  }
  function apply() {
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach(el => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-title]").forEach(el => {
      el.title = t(el.getAttribute("data-i18n-title"));
    });
    document.querySelectorAll("[data-lang]").forEach(b => {
      b.classList.toggle("is-on", b.getAttribute("data-lang") === lang);
    });
    try {
      window.dispatchEvent(new CustomEvent("vexora-lang", {
        detail: lang
      }));
    } catch (e) {}
  }
